/**
 * Rút ngẫu nhiên một quẻ xăm đầu năm từ 12 quẻ truyền thống.
 */
export function drawRandomFortuneSlip(): FortuneSlip {
  const randomIndex = Math.floor(Math.random() * FORTUNE_SLIPS.length);
  return FORTUNE_SLIPS[randomIndex];
}

/**
 * Tra cứu quẻ xăm theo số thứ tự ID (1 -> 12).
 * Nếu không tìm thấy ID tương ứng sẽ trả về Quẻ số 1 mặc định.
 */
export function getFortuneSlipById(id: number): FortuneSlip {
  return FORTUNE_SLIPS.find((slip) => slip.id === id) ?? FORTUNE_SLIPS[0];
}
